import { useState } from "react";
import { MessageCircleQuestion } from "lucide-react";
import { PREDEFINED_QUESTIONS, answerPredefinedQuestion, type PackageRecommendation, type PredefinedQuestion } from "@/lib/planner";
import type { PlannerRequirements } from "@/types/planner";

/**
 * "Have a question about these packages?" section (Phase 3, item 20).
 * Answers are computed deterministically from the already-scored
 * recommendations — no LLM call. Structured so a real AI service could
 * later replace `answerPredefinedQuestion` behind this same UI.
 */
const PlannerQuestions = ({
  recommendations,
  requirements,
}: {
  recommendations: PackageRecommendation[];
  requirements: PlannerRequirements;
}) => {
  const [active, setActive] = useState<PredefinedQuestion | null>(null);

  return (
    <div className="glass-card p-6 sm:p-8">
      <div className="flex items-center gap-2 mb-4">
        <MessageCircleQuestion className="text-gold" size={20} />
        <h3 className="font-display text-lg font-semibold">Have a question about these packages?</h3>
      </div>
      <div className="flex flex-wrap gap-2 mb-4">
        {PREDEFINED_QUESTIONS.map((q) => (
          <button
            key={q}
            type="button"
            onClick={() => setActive(q)}
            className={`text-xs sm:text-sm px-3 py-2 rounded-lg border transition-colors ${
              active === q ? "border-gold bg-gold/10 text-gold-dark" : "border-border hover:border-gold/50"
            }`}
          >
            {q}
          </button>
        ))}
      </div>
      {active && (
        <div className="text-sm text-foreground/90 bg-muted/40 border border-border rounded-lg p-4 leading-relaxed">
          {answerPredefinedQuestion(active, recommendations, requirements)}
        </div>
      )}
      <p className="text-xs text-muted-foreground mt-4">
        Answers are calculated directly from package data — not generated by an AI model.
      </p>
    </div>
  );
};

export default PlannerQuestions;
